package vectors

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func corpus(t *testing.T) (string, Lock) {
	t.Helper()
	root := t.TempDir()
	data := []byte("generated bootstrap control\n")
	if err := os.WriteFile(filepath.Join(root, "control.bin"), data, 0600); err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(data)
	manifest := Manifest{Schema: 1, Files: []Entry{{Path: "control.bin", Size: int64(len(data)), SHA256: hex.EncodeToString(sum[:])}}}
	raw, err := json.Marshal(manifest)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "manifest.json"), raw, 0600); err != nil {
		t.Fatal(err)
	}
	digest := sha256.Sum256(raw)
	return root, Lock{Schema: 1, Repository: Repository, Commit: strings.Repeat("a", 40), ManifestSHA256: hex.EncodeToString(digest[:])}
}

// Missing/changed/unlisted data refuse; restoring exact generated bytes passes.
// This proves fixture integrity only, not witness protocol conformance.
func TestVectorManifestRejectsMissingOrChangedBytes(t *testing.T) {
	for _, mode := range []string{"missing", "changed", "same-size", "extra"} {
		t.Run(mode, func(t *testing.T) {
			root, _ := corpus(t)
			if n, err := Check(root, nil, ""); err != nil || n != 1 {
				t.Fatalf("valid control: %d %v", n, err)
			}
			path := filepath.Join(root, "control.bin")
			original, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			switch mode {
			case "missing":
				err = os.Remove(path)
			case "changed":
				err = os.WriteFile(path, append(original, 'x'), 0600)
			case "same-size":
				changed := append([]byte(nil), original...)
				changed[0] ^= 1
				err = os.WriteFile(path, changed, 0600)
			case "extra":
				err = os.WriteFile(filepath.Join(root, "extra.bin"), []byte("extra"), 0600)
			}
			if err != nil {
				t.Fatal(err)
			}
			want := map[string]string{"missing": "vector_missing_or_link", "changed": "vector_digest_mismatch", "same-size": "vector_digest_mismatch", "extra": "vector_undeclared"}[mode]
			if _, err = Check(root, nil, ""); err == nil || err.Error() != want {
				t.Fatal("missing vector integrity refusal", err)
			}
			if mode == "extra" {
				err = os.Remove(filepath.Join(root, "extra.bin"))
			} else {
				err = os.WriteFile(path, original, 0600)
			}
			if err != nil {
				t.Fatal(err)
			}
			if _, err = Check(root, nil, ""); err != nil {
				t.Fatal("restored control", err)
			}
		})
	}
}

// Required metadata members have exact names and non-null values, even when a
// numeric zero would otherwise be a valid Go default. Exact objects still pass.
func TestVectorMetadataRequiresExactFields(t *testing.T) {
	for _, body := range []string{
		`{"Schema":1,"files":[]}`,
		`{"schema":1,"files":[{"path":"empty.bin","sha256":"` + digest(nil) + `"}]}`,
		`{"schema":1,"files":[{"path":"empty.bin","size":null,"sha256":"` + digest(nil) + `"}]}`,
	} {
		root := t.TempDir()
		if err := os.WriteFile(filepath.Join(root, "empty.bin"), nil, 0600); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(root, "manifest.json"), []byte(body), 0600); err != nil {
			t.Fatal(err)
		}
		if _, err := Check(root, nil, ""); err == nil || err.Error() != "metadata_fields" {
			t.Fatal("missing exact-field refusal", err)
		}
	}
	root, lock := corpus(t)
	path := filepath.Join(t.TempDir(), "lock.json")
	raw, err := json.Marshal(lock)
	if err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(path, raw, 0600); err != nil {
		t.Fatal(err)
	}
	parsed, err := ReadLock(path)
	if err != nil {
		t.Fatal("valid lock", err)
	}
	if _, err = Check(root, &parsed, lock.Commit); err != nil {
		t.Fatal("valid locked bytes", err)
	}
	for _, example := range []struct{ body, code string }{
		{strings.Replace(string(raw), `"schema"`, `"Schema"`, 1), "metadata_fields"},
		{strings.Replace(string(raw), `"schema":1`, `"schema":null`, 1), "metadata_fields"},
		{strings.Replace(string(raw), `"schema":1`, `"schema":1,"schema":1`, 1), "metadata_duplicate"},
	} {
		if err = os.WriteFile(path, []byte(example.body), 0600); err != nil {
			t.Fatal(err)
		}
		if _, err = ReadLock(path); err == nil || err.Error() != example.code {
			t.Fatal("missing closed-lock refusal", err)
		}
	}
}

// A consumer lock binds both exact manifest bytes and the externally obtained
// checkout commit; neither a digest-only nor commit-only match is sufficient.
func TestVectorLockRejectsWrongIdentity(t *testing.T) {
	for _, mode := range []string{"commit", "digest", "repository", "placeholder"} {
		t.Run(mode, func(t *testing.T) {
			root, lock := corpus(t)
			commit := lock.Commit
			if _, err := Check(root, &lock, commit); err != nil {
				t.Fatal("valid pinned control", err)
			}
			switch mode {
			case "commit":
				lock.Commit = strings.Repeat("b", 40)
			case "digest":
				lock.ManifestSHA256 = strings.Repeat("0", 64)
			case "repository":
				lock.Repository = "example.invalid/other"
			case "placeholder":
				lock.Commit = "<reviewed-commit>"
			}
			if _, err := Check(root, &lock, commit); err == nil || err.Error() != "vector_lock_mismatch" {
				t.Fatal("missing lock identity refusal", err)
			}
		})
	}
}

// Metadata is closed, duplicate-aware and path-contained; links cannot stand in
// for a declared regular vector. These are metadata checks, not CCJ-1 wire rules.
func TestVectorMetadataRejectsAmbiguityAndEscape(t *testing.T) {
	for _, example := range []struct{ body, code string }{
		{`{"schema":1,"schema":1,"files":[]}`, "metadata_duplicate"},
		{`{"schema":1,"files":[],"extra":true}`, "metadata_fields"},
		{`{"schema":1,"files":[{"path":"../escape","size":0,"sha256":"` + strings.Repeat("0", 64) + `"}]}`, "vector_path"},
	} {
		root := t.TempDir()
		if err := os.WriteFile(filepath.Join(root, "manifest.json"), []byte(example.body), 0600); err != nil {
			t.Fatal(err)
		}
		if _, err := Check(root, nil, ""); err == nil || err.Error() != example.code {
			t.Fatal("ambiguous or escaping metadata refusal", err)
		}
	}
	root, _ := corpus(t)
	path := filepath.Join(root, "control.bin")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(t.TempDir(), "control.bin")
	if err = os.WriteFile(target, data, 0600); err != nil {
		t.Fatal(err)
	}
	if err = os.Remove(path); err != nil {
		t.Fatal(err)
	}
	if err = os.Symlink(target, path); err != nil {
		t.Fatal(err)
	}
	if _, err = Check(root, nil, ""); err == nil || err.Error() != "vector_missing_or_link" {
		t.Fatal("missing linked-vector refusal", err)
	}
	if err = os.Remove(path); err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(path, data, 0600); err != nil {
		t.Fatal(err)
	}
	if _, err = Check(root, nil, ""); err != nil {
		t.Fatal("regular positive", err)
	}
}
